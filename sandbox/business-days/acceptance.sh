#!/usr/bin/env bash
# ============================================================================
# acceptance.sh — 検収条件の受入検査
#
# specs/002-business-days/spec.md 第2節の5件を、コマンドを実際に実行して
# 確かめる。画面を持たない対象なので、動いた事実は標準出力と終了コードで示す。
#
# 使い方: bash acceptance.sh
# 終了コード: 0 = 5件すべて通過 / 1 = 1件でも落ちた
#
# 手順の数を減らさないこと。spec.md 第2節と1対1で対応している。
# ============================================================================
set -u

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
CLI="node $HERE/src/cli.js"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fail=0
n=0

check() { # <番号> <説明> <期待する標準出力> <期待する終了コード> <実際の標準出力> <実際の終了コード>
  n=$((n + 1))
  if [ "$5" = "$3" ] && [ "$6" = "$4" ]; then
    printf 'ok   %s %s\n' "$1" "$2"
  else
    printf 'FAIL %s %s\n' "$1" "$2"
    printf '       期待: 出力=%s 終了コード=%s\n' "$3" "$4"
    printf '       実際: 出力=%s 終了コード=%s\n' "$5" "$6"
    fail=$((fail + 1))
  fi
}

# --- User Story 1 ---------------------------------------------------------

# 検収条件1: 休業日なし。2026-09-01(火) 〜 2026-09-07(月) は 5 営業日
out=$($CLI 2026-09-01 2026-09-07 2>/dev/null); rc=$?
check 1 "休業日なしで 5 営業日" "5" "0" "$out" "$rc"

# 検収条件2: 2026-09-03 を休業日にすると 4 営業日
printf '2026-09-03\n' > "$TMP/holidays.txt"
out=$($CLI 2026-09-01 2026-09-07 "$TMP/holidays.txt" 2>/dev/null); rc=$?
check 2 "休業日1件で 4 営業日" "4" "0" "$out" "$rc"

# 検収条件3: 土曜日だけの期間は 0 営業日
out=$($CLI 2026-09-05 2026-09-05 2>/dev/null); rc=$?
check 3 "土曜日だけなら 0 営業日" "0" "0" "$out" "$rc"

# --- User Story 2: 停止4領域「日付」 --------------------------------------

# 検収条件4: 存在しない日付は数値を出さずに終了コード 1
out=$($CLI 2026-02-30 2026-09-07 2>/dev/null); rc=$?
check 4 "存在しない日付で止まる" "" "1" "$out" "$rc"

# 検収条件5: 開始日が終了日より後なら数値を出さずに終了コード 1
out=$($CLI 2026-09-10 2026-09-01 2>/dev/null); rc=$?
check 5 "開始日が終了日より後で止まる" "" "1" "$out" "$rc"

# --- 集計 -----------------------------------------------------------------

printf '\n1..%s\n' "$n"
if [ "$fail" -gt 0 ]; then
  printf 'RESULT: FAIL (%s / %s 件が落ちた)\n' "$fail" "$n"
  exit 1
fi
printf 'RESULT: PASS (%s / %s 件)\n' "$n" "$n"
exit 0
